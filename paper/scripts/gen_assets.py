"""Generate manuscript metrics and tables from traceable experiment records."""



import argparse

import hashlib

import json

from pathlib import Path





ROOT = Path(__file__).resolve().parents[1]

EXPERIMENTS = ROOT.parent / "experiments"





def digest(path):

    return hashlib.sha256(path.read_bytes()).hexdigest()





def read_record(relative, sources):

    path = EXPERIMENTS / relative
    if not path.exists():
        path = ROOT / "evidence/source-records" / relative

    sources.append(dict(path=relative, bytes=path.stat().st_size, sha256=digest(path)))

    return json.loads(path.read_text(encoding="utf-8-sig"))





def snapshot():

    sources = []

    legacy = read_record("legacy_repair_20261016/OVERALL_SUMMARY.json", sources)

    classification = read_record("precision_audit_20261016/CLASSIFICATION.json", sources)

    alias = read_record("precision_audit_20261016/ALIAS_ORACLE_AUDIT.json", sources)

    rpc = read_record("e2e_20261016/OVERALL_SUMMARY.json", sources)

    hdfs = read_record("m0_hdfs_20261016/OVERALL_SUMMARY.json", sources)

    tomcat = read_record("precision_partition_20261017/runtime_baseline/RUNTIME_REPORT.json", sources)

    em3d = read_record("em3d_next_merge_20261110/OBSERVATIONS.json", sources)

    validation = read_record("em3d_next_merge_20261110/VERIFICATION.json", sources)

    em3d_graph = read_record("precision_partition_20261017/measurements/em3d_final/graph.json", sources)

    semantic = {

        "programs": legacy["rq1"]["total"], "violations": legacy["rq1"]["violations"],

        "exact": legacy["rq1"]["exact_matches"], "families": legacy["rq1_by_family"],

        "schedules": sum(v["schedules"] for v in legacy["rq1_by_family"].values()),

        "refinement": classification["metadata_ablation_counts"],

        "origins": {

            k: {name: value for name, value in row.items() if name != "program_ids"}

            for k, row in classification["origin_categories"].items()

        },

        "alias_envelope": alias["summary"],

    }

    layout = {k: legacy["rq2"][k] for k in (

        "planned_runs", "completed_programs", "successes", "mismatches", "runs_with_cut_edges",

        "duplicate_messages", "serialized_messages", "workers", "strategies", "schedule_seeds",

    )}

    rows = []

    for row in em3d["runs"]:

        rows.append({key: row[key] for key in (

            "case", "mode", "workers", "rounds", "partition_sha256", "totals", "by_scope",

            "next_heap_residual_rounds", "next_load_residual_rounds", "trace",

        )})

    data = dict(

        semantic=semantic, layout=layout,

        rpc=dict(runtime=rpc["runtime"], totals=rpc["totals"],

                 cases=[{k: r[k] for k in ("framework", "scenario", "planned", "passed", "mutation_checks")} for r in rpc["cases"]]),

        hdfs=dict(M0=hdfs["M0"], M1=hdfs["M1"]),

        tomcat={k: tomcat[k] for k in (

            "relation_count", "total_tuples", "all71_canonical_byte_comparisons_equal",

            "phase_timings", "spark_controls", "rule_dependency_graph",

        )},

        em3d=dict(run_count=em3d["run_count"], distinct_maps=em3d["distinct_owner_maps"],

                  variables=em3d_graph["n_variables"], objects=em3d_graph["n_allocations"], fields=len(em3d_graph["fields"]),

                  checkpoints=sum(len(row["rounds"]) for row in validation["runs"]),

                  variable_facts=validation["runs"][0]["final_variable_facts"],

                  heap_facts=validation["runs"][0]["final_heap_facts"],

                  full_scan=validation["runs"][0]["final_full_scan"],

                  legacy_replays=validation["matching_legacy_native_replays"], runs=rows),

        sources=sources,

    )

    return data





def number(value):

    return f"{value:,}" if isinstance(value, int) else str(value)





def table(filename, caption, label, alignment, headers, rows):

    content = ["% Generated by scripts/gen_assets.py", "\\begin{table}[t]", "\\centering", "\\small",

               f"\\caption{{{caption}}}", f"\\label{{{label}}}",

               "\\begin{tabular}{" + alignment + "}", "\\toprule",

               " & ".join("\\textbf{" + text + "}" for text in headers) + " \\\\", "\\midrule"]

    content.extend(" & ".join(map(str, row)) + " \\\\" for row in rows)

    content.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}", ""])

    (ROOT / "Tables" / filename).write_text("\n".join(content), encoding="utf-8")





def generate(data):

    semantic, layout, rpc, hdfs, tomcat, em3d = (data[k] for k in ("semantic", "layout", "rpc", "hdfs", "tomcat", "em3d"))

    first = em3d["runs"][0]

    causal = first["by_scope"]["next"]

    downstream = first["by_scope"]["downstream"]

    counts = dict(

        nSemanticPrograms=semantic["programs"], nSemanticSchedules=semantic["schedules"],

        nSemanticExact=semantic["exact"], nSemanticConservative=semantic["programs"]-semantic["exact"],

        nSemanticViolations=semantic["violations"], nEnvelopeChoices=semantic["alias_envelope"]["enumerated_concreteizations"],

        nEnvelopeSchedules=semantic["alias_envelope"]["summed_legal_schedules"],

        nLayoutPrograms=layout["completed_programs"], nLayoutRuns=layout["planned_runs"],

        nLayoutPolicies=len(layout["strategies"]), nLayoutSeeds=len(layout["schedule_seeds"]),

        nLayoutWorkerCounts=len(layout["workers"]), nLayoutMismatches=layout["mismatches"],

        nLayoutCutRuns=layout["runs_with_cut_edges"], nLayoutMessages=layout["serialized_messages"],

        nLayoutDuplicateMessages=layout["duplicate_messages"], nRpcCases=len(rpc["cases"]),

        nRpcConfigurations=rpc["totals"]["planned"], nRpcMutations=rpc["totals"]["mutation_checks"],

        nHdfsMethods=hdfs["M1"]["real_methods_extracted_per_variant"],

        nHdfsRuntime=hdfs["M1"]["actual_runtime_outcomes_matched"],

        nHdfsSourceRows=hdfs["M1"]["source_projection_rows_equal"],

        nHdfsHeldOut=hdfs["M1"]["held_out_rows_checked"],

        nTomcatRelations=tomcat["relation_count"], nTomcatTuples=tomcat["total_tuples"],

        nEmRuns=em3d["run_count"], nEmMaps=em3d["distinct_maps"], nEmCheckpoints=em3d["checkpoints"],

        nEmVariables=em3d["variables"], nEmObjects=em3d["objects"], nEmFields=em3d["fields"],

        nEmWorkerStarts=sum(row["workers"] for row in em3d["runs"]),

        nEmNativeRuns=len(em3d["legacy_replays"]),

        nEmVariableFacts=em3d["variable_facts"], nEmHeapFacts=em3d["heap_facts"],

        nEmCandidates=first["totals"]["fact_candidates"], nEmDuplicateFacts=first["totals"]["duplicate_facts"],

        nEmActivations=first["totals"]["base_activations"], nEmNextEdges=causal["installed"],

        nEmNextCandidates=causal["accepted"]+causal["duplicate_fact"], nEmNextAccepted=causal["accepted"],

        nEmNextDuplicates=causal["duplicate_fact"], nEmChainCandidates=causal["accepted"]+causal["duplicate_fact"]+downstream["accepted"]+downstream["duplicate_fact"],

        nEmChainAccepted=causal["accepted"]+downstream["accepted"],

        nEmFullScanRules=em3d["full_scan"]["rhs_checks"],

    )

    (ROOT / "Tex" / "results.tex").write_text(

        "% Generated by scripts/gen_assets.py\n" + "\n".join("\\newcommand{\\" + name + "}{" + number(value) + "}" for name, value in counts.items()) + "\n",

        encoding="utf-8",

    )

    table("semantic-results.tex", "Finite semantic observations under complete legal-schedule enumeration. Exactness compares scalar-value sets and may-taint projections.", "tab:semantic-results", "lrrrr",

          ["Program family", "Programs", "Schedules", "Exact", "Conservative"],

          [[label, number(row["programs"]), number(row["schedules"]), number(row["exact"]), number(row["imprecise"])] for label, row in semantic["families"].items()] +

          [["Total", number(semantic["programs"]), number(semantic["schedules"]), number(semantic["exact"]), number(semantic["programs"]-semantic["exact"])]] )

    refinement = semantic["refinement"]

    table("precision-controls.tex", "Address-information controls on the same finite program corpus. All rows preserve the concrete execution semantics.", "tab:precision-controls", "lrr",

          ["Static address information", "Exact programs", "Conservative programs"],

          [[label, number(refinement[key]["exact"]), number(semantic["programs"]-refinement[key]["exact"])] for label, key in (

              ("Declared address envelope", "baseline"), ("Precise read addresses", "precise_reads"),

              ("Precise write addresses", "precise_writes"), ("Precise read and write addresses", "precise_all"))])

    table("reference-coverage.tex", "Execution and reference scopes. Each row has its own unit of observation, so counts are not pooled.", "tab:reference-coverage", "p{.20\\linewidth}p{.30\\linewidth}p{.40\\linewidth}",

          ["Input", "Validated extent", "Execution and semantic scope"], [

              ["Dubbo / gRPC", f"{number(len(rpc['cases']))} cases, {number(rpc['totals']['planned'])} configurations", "Real RPC examples with restricted extracted transfer models"],

              ["HDFS fsync", f"{number(hdfs['M1']['real_methods_extracted_per_variant'])} methods, {number(hdfs['M1']['source_projection_rows_equal'])} source-reference rows", "Real cross-JVM RPC, explicit finite heap and library contracts"],

              ["Em3d / BH / MST", "Complete variable and heap relations", "Application-only Spark PAGs and stock Souffl\\'e cross-checks"],

              ["Tomcat", f"{number(tomcat['relation_count'])} relations, {number(tomcat['total_tuples'])} tuples", "Public DOOP facts, single-process Souffl\\'e, one/four threads"],

          ])

    by_key = {(row["case"], row["mode"]):row for row in em3d["runs"]}

    names = {"reference_k1":"Single", "hash_k2_s1_r0":"Hash, seed 1", "hash_k2_s2_r0":"Hash, seed 2", "method_k2_s1_r0":"Method", "metis_cut_k2_s1_r0":"METIS cut", "hash_k4_s1_r0":"Hash", "metis_cut_k4_s1_r0":"METIS cut"}

    rows = []

    for case in ("reference_k1", "hash_k2_s1_r0", "hash_k2_s2_r0", "method_k2_s1_r0", "metis_cut_k2_s1_r0", "hash_k4_s1_r0", "metis_cut_k4_s1_r0"):

        row = by_key[case,"drain"]

        cross = sum(scope.get("cross_E",0)+scope.get("cross_F",0) for scope in row["by_scope"].values())

        rows.append([names[case], row["workers"], by_key[case,"frontier"]["rounds"], row["rounds"], number(cross), number(row["totals"]["fact_candidates"])])

    table("em3d-layouts.tex", "Representative Em3d owner maps. Frontier and Drain report rounds. Omitted second-seed rows have the same displayed counts. Cross-owner events count edge requests and fact candidates, excluding diagnostic traffic.", "tab:em3d-layouts", "lrrrrr",

          ["Owner map", "Workers", "Frontier", "Drain", "Cross events", "Candidates"], rows)

    table("em3d-repair.tex", "Observed incremental work per Em3d execution. Installations and candidate checks are distinct operation units. The downstream row excludes the direct next operations.", "tab:em3d-repair", "lrrrr",

          ["Scope", "New edges", "Candidates", "Accepted", "Duplicate"], [

              ["Direct next", causal["installed"], causal["accepted"]+causal["duplicate_fact"], causal["accepted"], causal["duplicate_fact"]],

              ["Copies and iterator write", downstream["installed"], downstream["accepted"]+downstream["duplicate_fact"], downstream["accepted"], downstream["duplicate_fact"]],

              ["Whole analysis", first["totals"]["installed_edges"], first["totals"]["fact_candidates"], em3d["variable_facts"]+em3d["heap_facts"], first["totals"]["duplicate_facts"]],

          ])

    (ROOT / "evidence" / "CLAIMS.json").write_text(json.dumps(dict(

        status="SUPPORTED_WITH_EXPLICIT_SCOPES", sources=data["sources"], generated_macros=counts,

        constraints=["Finite semantic exactness is scalar/may-taint projected equality", "Layout runs use discrete-event simulation", "Tomcat uses one shared-memory process", "Em3d uses independent processes on one physical host", "No measured new-algorithm speedup or general merge-check bottleneck"],

    ), indent=2)+"\n", encoding="utf-8")





def main():

    parser = argparse.ArgumentParser(description=__doc__)

    parser.add_argument("--refresh", action="store_true", help="refresh snapshots from the sibling experiment directory")

    args = parser.parse_args()

    for directory in ("Tex", "Tables", "evidence"):

        (ROOT / directory).mkdir(parents=True, exist_ok=True)

    path = ROOT / "evidence" / "results.json"

    if args.refresh or not path.exists():

        path.write_text(json.dumps(snapshot(), indent=2)+"\n", encoding="utf-8")

    generate(json.loads(path.read_text(encoding="utf-8")))

    print("Generated result macros and five tables from evidence/results.json")





if __name__ == "__main__":

    main()

